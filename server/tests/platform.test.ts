import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import request from 'supertest';
import { parseInboundSms } from '../src/controllers/sms.controller';
import { api, clearDb, createReport, createSos, makeUser, startDb, stopDb } from './helpers';
import { Emergency } from '../src/models';

describe('inbound SMS parsing (unit)', () => {
  it('parses the format generated by the app', () => {
    expect(parseInboundSms('RESQ FLOOD 4 13.0827,80.2707 water rising fast')).toEqual({ type: 'flood', affected: 4, lat: 13.0827, lng: 80.2707, text: 'water rising fast' });
  });
  it('maps unknown types to "other" and rejects unparseable text or impossible coordinates', () => {
    expect(parseInboundSms('RESQ ALIEN 2 13.0,80.0')?.type).toBe('other');
    expect(parseInboundSms('help me please')).toBeNull();
    expect(parseInboundSms('RESQ FLOOD 4 95.0,80.0 x')).toBeNull();
  });
});

beforeAll(startDb);
afterAll(stopDb);
beforeEach(clearDb);

describe('API error handling', () => {
  it('returns the consistent JSON error shape for unknown routes, bad JSON and invalid ids', async () => {
    const admin = await makeUser('admin');
    const nf = await request(api()).get('/api/nope');
    expect(nf.status).toBe(404);
    expect(nf.body).toMatchObject({ success: false, error: { code: 'ROUTE_NOT_FOUND' } });
    const bad = await request(api()).post('/api/auth/login').set('Content-Type', 'application/json').send('{"email": ');
    expect(bad.status).toBe(400);
    expect(bad.body.error.code).toBe('INVALID_JSON');
    const id = await request(api()).get('/api/emergencies/not-an-id').set(admin.auth);
    expect(id.status).toBe(400);
    expect(id.body.success).toBe(false);
    const missing = await request(api()).get('/api/emergencies/64b7f0f0f0f0f0f0f0f0f0f0').set(admin.auth);
    expect(missing.status).toBe(404);
    expect(missing.body.error.code).toBe('EMERGENCY_NOT_FOUND');
  });

  it('never leaks stack traces', async () => {
    const res = await request(api()).get('/api/nope');
    expect(JSON.stringify(res.body)).not.toMatch(/node_modules|\.ts:/);
  });

  it('reports health without authentication', async () => {
    const res = await request(api()).get('/api/health');
    expect(res.status).toBe(200);
    expect(res.body.data.status).toBe('ok');
  });
});

describe('inbound SMS webhook is honest about being optional', () => {
  it('answers 501 when no gateway secret is configured', async () => {
    const res = await request(api()).post('/api/sms/inbound').send({ from: '+919800000000', body: 'RESQ FLOOD 2 13.0,80.2 help' });
    expect(res.status).toBe(501);
    expect(res.body.error.code).toBe('SMS_INBOUND_NOT_CONFIGURED');
    expect(await Emergency.countDocuments()).toBe(0);
  });
});

describe('real-time-ready map data with role-based visibility (Feature 12)', () => {
  it('shows each citizen only their own emergencies, admins everything, and filters by type/priority/status', async () => {
    const a = await makeUser('citizen');
    const b = await makeUser('citizen', 'other');
    const admin = await makeUser('admin');
    await createSos(a);
    await createReport(b, { type: 'fire', description: 'Fire in the warehouse next door', affectedCount: 2, contact: { phone: '+919800000001' }, location: { lat: 13.1, lng: 80.3 } });
    expect((await request(api()).get('/api/map').set(a.auth)).body.data.emergencies).toHaveLength(1);
    expect((await request(api()).get('/api/map').set(b.auth)).body.data.emergencies).toHaveLength(1);
    const all = await request(api()).get('/api/map').set(admin.auth);
    expect(all.body.data.emergencies).toHaveLength(2);
    expect(all.body.data.emergencies.find((e: { kind: string }) => e.kind === 'sos')).toMatchObject({ priority: expect.any(String), lat: expect.any(Number) });
    expect((await request(api()).get('/api/map?type=fire').set(admin.auth)).body.data.emergencies).toHaveLength(1);
    expect((await request(api()).get('/api/map?status=resolved').set(admin.auth)).body.data.emergencies).toHaveLength(0);
  });

  it('does not expose contact details on the map and keeps team locations away from citizens', async () => {
    const citizen = await makeUser('citizen');
    const admin = await makeUser('admin');
    await createSos(citizen);
    const res = await request(api()).get('/api/map').set(admin.auth);
    expect(JSON.stringify(res.body.data.emergencies)).not.toMatch(/phone|919822222222/);
    const cm = await request(api()).get('/api/map').set(citizen.auth);
    expect(cm.body.data.teams).toEqual([]);
  });
});

describe('notifications', () => {
  it('are private per user and can be marked read', async () => {
    const citizen = await makeUser('citizen');
    const admin = await makeUser('admin');
    await createSos(citizen);
    const list = await request(api()).get('/api/notifications').set(admin.auth);
    expect(list.body.data.length).toBeGreaterThan(0);
    expect((await request(api()).get('/api/notifications').set(citizen.auth)).body.data).toHaveLength(0);
    const id = list.body.data[0].id;
    expect((await request(api()).post(`/api/notifications/${id}/read`).set(citizen.auth)).status).toBe(404);
    expect((await request(api()).post(`/api/notifications/${id}/read`).set(admin.auth)).status).toBe(200);
    expect((await request(api()).post('/api/notifications/read-all').set(admin.auth)).status).toBe(200);
    expect((await request(api()).get('/api/notifications?unread=true').set(admin.auth)).body.data).toHaveLength(0);
  });
});

describe('admin settings and dashboards', () => {
  it('validates settings and exposes dashboard statistics', async () => {
    const admin = await makeUser('admin');
    const citizen = await makeUser('citizen');
    await createSos(citizen);
    expect((await request(api()).put('/api/admin/settings').set(admin.auth).send({ ackDeadlineSeconds: 1 })).status).toBe(400);
    expect((await request(api()).put('/api/admin/settings').set(admin.auth).send({ priority: { thresholds: { critical: 10, high: 20, medium: 30 } } })).status).toBe(400);
    expect((await request(api()).put('/api/admin/settings').set(admin.auth).send({ smsEmergencyNumber: '+911234567890' })).body.data.smsEmergencyNumber).toBe('+911234567890');
    expect((await request(api()).get('/api/config/public')).body.data.smsEmergencyNumber).toBe('+911234567890');
    const stats = await request(api()).get('/api/admin/stats').set(admin.auth);
    expect(stats.status).toBe(200);
    expect(stats.body.data.activeSos ?? stats.body.data.sos?.active).toBeGreaterThanOrEqual(1);
  });

  it('lets admins list, create and update users with an audit trail', async () => {
    const admin = await makeUser('admin');
    const created = await request(api()).post('/api/users').set(admin.auth).send({ name: 'Lead Person', email: 'lead@example.com', password: 'Strong#123', role: 'team_leader' });
    expect(created.status).toBe(201);
    const list = await request(api()).get('/api/users?role=team_leader&search=lead').set(admin.auth);
    expect(list.body.data).toHaveLength(1);
    const upd = await request(api()).patch(`/api/users/${created.body.data.id}`).set(admin.auth).send({ status: 'suspended' });
    expect(upd.body.data.status).toBe('suspended');
    expect((await request(api()).get('/api/admin/audit?action=user.update').set(admin.auth)).body.data).toHaveLength(1);
  });
});
